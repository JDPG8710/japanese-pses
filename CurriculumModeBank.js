function buildMatchQuestions(mode, groups) {
  return groups.flatMap(group => {
    const answers = group.map(([, answer]) => String(answer));
    return group.map(([prompt, answer], index) => makeQuestion(
      mode,
      prompt,
      answer,
      [answers[(index + 1) % 4], answers[(index + 2) % 4], answers[(index + 3) % 4]]
    ));
  });
}

function buildSequenceQuestions(mode, sequences) {
  return sequences.flatMap(({ title, steps }) => [
    makeQuestion(mode, `${title}で最初に行うことは？`, steps[0], [steps[1], steps[2], steps[3]]),
    makeQuestion(mode, `${title}で「${steps[0]}」の次は？`, steps[1], [steps[0], steps[2], steps[3]]),
    makeQuestion(mode, `${title}で「${steps[1]}」の次は？`, steps[2], [steps[0], steps[1], steps[3]]),
    makeQuestion(mode, `${title}で最後に行うことは？`, steps[3], [steps[0], steps[1], steps[2]])
  ]);
}

