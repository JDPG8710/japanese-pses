const GRADE1_KATAKANA = [...'アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン'];

function buildKanaPairQuestions(mode, prompts, answers) {
  return answers.map((answer, index) => {
    const distractors = [1, 5, 11].map(offset => answers[(index + offset) % answers.length]);
    return makeQuestion(
      mode,
      mode === 'HIRAGANA'
        ? `カタカナ「${prompts[index]}」と おなじ おとの ひらがなは？`
        : `ひらがな「${prompts[index]}」と おなじ おとの カタカナは？`,
      answer,
      distractors,
      `「${prompts[index]}」と「${answer}」は、おなじ おとです。`
    );
  });
}

