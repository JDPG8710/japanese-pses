const MIXED_MODES = new Set([
  'MIXED_CURRICULUM', 'SOCIAL_MIXED',
  'GRADE_1_LAB', 'GRADE_2_LAB', 'GRADE_3_LAB', 'GRADE_4_LAB', 'GRADE_5_LAB', 'GRADE_6_LAB'
]);

export function getCurriculumModePolicy(subject, selectedMode) {
  const mode = String(selectedMode || '');
  if (!mode || MIXED_MODES.has(mode)) return { strict: false, modes: [] };
  const quizModes = {
    '国語': new Set(['HIRAGANA', 'KATAKANA', 'READ_ALOUD', 'READING_QUIZ']),
    '社会': new Set(['MAP_GAME', 'SEQUENCE_GAME']),
    '生活': new Set(['OBSERVATION_SEQUENCE', 'COMMUNITY_MATCH']),
    '理科': new Set([
      'MAGNET_LAB', 'LIGHT_SOUND_LAB', 'LIFE_CYCLE_SORT',
      'AIR_WATER_LAB', 'MUSCLE_MODEL',
      'ELECTROMAGNET_LAB', 'SOLUBILITY_LAB', 'GERMINATION_LAB', 'RIVER_WEATHER_LAB',
      'AQUEOUS_LAB', 'COMBUSTION_LAB', 'PHOTOSYNTHESIS_LAB', 'ENERGY_LAB', 'MOON_REASONING'
    ])
  };
  return quizModes[subject]?.has(mode)
    ? { strict: true, modes: [mode] }
    : { strict: false, modes: [] };
}

export function getSupplementalCurriculumQuestions(subject, grade) {
  const g = Math.max(1, Math.min(6, Number(grade) || 1));
  const records = subject === '国語'
    ? (KOKUGO_BANKS[g] || [])
    : subject === '理科'
    ? (SCIENCE_BANKS[g] || [])
    : subject === '社会'
      ? (SOCIAL_BANKS[g] || [])
      : subject === '生活'
        ? (LIFE_BANKS[g] || [])
        : [];
  return records.map((record, index) => ({
    ...record,
    id: `SUP_${subject}_G${g}_${record.mode}_${index}`,
    subject,
    grade: g
  }));
}

