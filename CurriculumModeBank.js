/**
 * 学年・教科・ゲーム選択を結ぶ唯一の題材契約。
 *
 * UI の selectedMode と問題の mode を同じ値にそろえ、選択した題材へ
 * 別単元の問題を混ぜない。固定クイズは各モード 12 問以上を持ち、
 * 10 問セッションを繰り返しても毎回同じ集合にならないようにする。
 */

const makeQuestion = (mode, prompt, correct, distractors, explanation = '') => ({
  mode,
  prompt,
  correct: String(correct),
  distractors: distractors.map(String),
  explanation
});

const rows = (mode, entries) => entries.map(([prompt, correct, ...distractors]) =>
  makeQuestion(mode, prompt, correct, distractors)
);

