function fillPartOptions(requiredParts, limit = 6) {
  const result = requiredParts.map(String);
  for (const candidate of PART_DISTRACTORS) {
    if (result.length >= limit) break;
    if (!result.includes(candidate)) result.push(candidate);
  }
  return result;
}

function makePuzzle(entry, index, grade) {
  const [target, reading, parts, radical, radicalName, structure] = entry;
  const type = ['ASSEMBLY', 'RADICAL_CHOICE', 'STRUCTURE_CHOICE'][index % 3];
  if (type === 'RADICAL_CHOICE') {
    return {
      id: `RADICAL_G${grade}_${index + 1}`,
      type,
      target,
      reading,
      prompt: `「${target}」の部首を選ぼう`,
      parts: [radical],
      options: fillPartOptions([radical]),
      hint: `「${target}」の部首は「${radicalName}」です。`
    };
  }
  if (type === 'STRUCTURE_CHOICE') {
    return {
      id: `RADICAL_G${grade}_${index + 1}`,
      type,
      target,
      reading,
      prompt: `「${target}」の組み立て方を選ぼう`,
      parts: [structure],
      options: [...STRUCTURE_OPTIONS],
      hint: `「${target}」は「${structure}」の組み立てです。`
    };
  }
  return {
    id: `RADICAL_G${grade}_${index + 1}`,
    type,
    target,
    reading,
    prompt: `「${target}」を正しいパーツで組み立てよう`,
    parts: [...parts],
    options: fillPartOptions(parts),
    hint: `${parts.join(' ＋ ')} で「${target}」になります。`
  };
}

export const RADICAL_PUZZLES_BY_GRADE = Object.freeze(Object.fromEntries(
  Object.entries(GRADE_RADICAL_SOURCE).map(([grade, entries]) => [
    Number(grade),
    Object.freeze(entries.map((entry, index) => Object.freeze(makePuzzle(entry, index, Number(grade)))))
  ])
));

export function getRadicalPuzzlesForGrade(grade) {
  const normalizedGrade = Math.max(1, Math.min(6, Number(grade) || 1));
  return RADICAL_PUZZLES_BY_GRADE[normalizedGrade].map(puzzle => ({
    ...puzzle,
    parts: [...puzzle.parts],
    options: [...puzzle.options]
  }));
}
